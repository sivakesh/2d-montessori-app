import 'package:flutter/foundation.dart';

import 'field_path.dart';
import 'source_hash.dart';

/// A translation's state. [missing] and [outdated] are never stored: they
/// are derived (no translation; or its English source changed since), so
/// they can't fall out of step with the content. The others are the stored
/// workflow state.
enum TranslationStatus {
  missing('missing'),
  draft('draft'),
  needsReview('needs_review'),
  approved('approved'),
  published('published'),
  outdated('outdated');

  const TranslationStatus(this.id);

  final String id;

  static const stored = [draft, needsReview, approved, published];

  /// A stored status; anything unrecognised is read as [draft] (never as
  /// approved or published).
  static TranslationStatus parseStored(Object? value) {
    for (final s in stored) {
      if (s.id == value) return s;
    }
    return draft;
  }
}

/// Where a translation's text came from.
enum TranslationOrigin {
  human('human'),

  /// Inline text from before translation records (e.g. existing Tamil).
  legacy('legacy'),

  /// Generated by an AI provider (a later phase; always needs review).
  ai('ai');

  const TranslationOrigin(this.id);

  final String id;

  static TranslationOrigin parse(Object? value) => values.firstWhere((o) => o.id == value, orElse: () => human);
}

/// One field's translation in one language. [sourceHash] is the
/// [SourceHash] of the English text it was made from; [previousText] keeps
/// the last approved or published text after an edit, until the new text
/// is published.
@immutable
class TranslationEntry {
  const TranslationEntry({
    required this.text,
    required this.status,
    required this.sourceHash,
    this.origin = TranslationOrigin.human,
    this.sourceRevision,
    this.previousText,
    this.updatedById = '',
    this.reviewedById = '',
  }) : assert(status != TranslationStatus.missing && status != TranslationStatus.outdated, 'derived statuses are never stored');

  /// A new manual translation of [source] (status draft).
  factory TranslationEntry.manual({required String text, required String source, String updatedById = '', int? sourceRevision}) =>
      TranslationEntry(text: text, status: TranslationStatus.draft, sourceHash: SourceHash.of(source), updatedById: updatedById, sourceRevision: sourceRevision);

  static TranslationEntry? fromMap(Object? map) {
    if (map is! Map || map['text'] is! String || map['sourceHash'] is! String) return null;
    return TranslationEntry(
      text: map['text'] as String,
      status: TranslationStatus.parseStored(map['status']),
      sourceHash: map['sourceHash'] as String,
      origin: TranslationOrigin.parse(map['origin']),
      sourceRevision: map['sourceRevision'] is int ? map['sourceRevision'] as int : null,
      previousText: map['previousText'] is String ? map['previousText'] as String : null,
      updatedById: map['updatedById']?.toString() ?? '',
      reviewedById: map['reviewedById']?.toString() ?? '',
    );
  }

  final String text;

  /// The stored workflow status (never missing or outdated).
  final TranslationStatus status;
  final String sourceHash;
  final TranslationOrigin origin;
  final int? sourceRevision;
  final String? previousText;
  final String updatedById;
  final String reviewedById;

  Map<String, dynamic> toMap() => {
        'text': text,
        'status': status.id,
        'sourceHash': sourceHash,
        'origin': origin.id,
        if (sourceRevision != null) 'sourceRevision': sourceRevision,
        if (previousText != null) 'previousText': previousText,
        if (updatedById.isNotEmpty) 'updatedById': updatedById,
        if (reviewedById.isNotEmpty) 'reviewedById': reviewedById,
      };

  /// The derived status against the English text [currentSource]: missing
  /// when there's no text; outdated when the English has changed since
  /// (the text is kept); otherwise the stored status.
  static TranslationStatus statusOf(TranslationEntry? entry, String currentSource) {
    if (entry == null || entry.text.trim().isEmpty) return TranslationStatus.missing;
    if (entry.sourceHash != SourceHash.of(currentSource)) return TranslationStatus.outdated;
    return entry.status;
  }

  /// Whether the stored status may move [from] → [to]: draft → needs
  /// review or approved; needs review → draft or approved; approved →
  /// published (only by publishing a language) or back to draft; published
  /// → draft (by editing). AI output can only enter as needs review.
  static bool canTransition(TranslationStatus from, TranslationStatus to) => switch ((from, to)) {
        (TranslationStatus.draft, TranslationStatus.needsReview) => true,
        (TranslationStatus.draft, TranslationStatus.approved) => true,
        (TranslationStatus.needsReview, TranslationStatus.draft) => true,
        (TranslationStatus.needsReview, TranslationStatus.approved) => true,
        (TranslationStatus.approved, TranslationStatus.published) => true,
        (TranslationStatus.approved, TranslationStatus.draft) => true,
        (TranslationStatus.published, TranslationStatus.draft) => true,
        _ => false,
      };

  TranslationEntry _moveTo(TranslationStatus to, {String? text, String? sourceHash, String? previousText, bool clearPrevious = false, String? reviewedById, String? updatedById}) {
    if (to != status && !canTransition(status, to)) throw StateError('A translation can’t go from ${status.id} to ${to.id}.');
    return TranslationEntry(
      text: text ?? this.text,
      status: to,
      sourceHash: sourceHash ?? this.sourceHash,
      origin: origin,
      sourceRevision: sourceRevision,
      previousText: clearPrevious ? null : (previousText ?? this.previousText),
      updatedById: updatedById ?? this.updatedById,
      reviewedById: reviewedById ?? this.reviewedById,
    );
  }

  /// [text] edited against the English [source]: back to draft, with the
  /// last approved or published text kept in [previousText].
  TranslationEntry edit(String text, {required String source, String updatedById = ''}) => _moveTo(
        TranslationStatus.draft,
        text: text,
        sourceHash: SourceHash.of(source),
        previousText: status == TranslationStatus.approved || status == TranslationStatus.published ? (previousText ?? this.text) : previousText,
        updatedById: updatedById,
        reviewedById: '',
      );

  TranslationEntry submitForReview() => _moveTo(TranslationStatus.needsReview);

  /// Approved — refused while outdated against [currentSource] (review it
  /// against the new English first).
  TranslationEntry approve({required String currentSource, String reviewedById = ''}) {
    if (statusOf(this, currentSource) == TranslationStatus.outdated) throw StateError('This translation is outdated: the English text has changed.');
    return _moveTo(TranslationStatus.approved, reviewedById: reviewedById);
  }

  /// Published (only by publishing a language): [previousText] is no
  /// longer needed.
  TranslationEntry markPublished() => _moveTo(TranslationStatus.published, clearPrevious: true);
}

/// All translations of one source document (a page, the site layout, an
/// image's text) into one language, keyed by [TranslationPath] value. Not
/// stored anywhere yet (a later phase adds the collections).
@immutable
class TranslationRecord {
  const TranslationRecord({required this.lang, required this.scope, required this.docId, this.fields = const {}});

  static const schemaVersion = 1;

  /// The document id a record would have: `<lang>__<scope>__<docId>`.
  static String idFor(String lang, String scope, String docId) => '${lang}__${scope}__$docId';

  /// Tolerant: entries that aren't usable (bad path or shape) are left out.
  static TranslationRecord? fromMap(Object? map) {
    if (map is! Map || map['lang'] is! String || map['scope'] is! String || map['docId'] is! String) return null;
    final raw = map['fields'];
    return TranslationRecord(
      lang: map['lang'] as String,
      scope: map['scope'] as String,
      docId: map['docId'] as String,
      fields: {
        if (raw is Map)
          for (final e in raw.entries)
            if (e.key is String && TranslationPath.tryParse(e.key as String) != null) e.key as String: ?TranslationEntry.fromMap(e.value),
      },
    );
  }

  final String lang;

  /// `page`, `builtin`, `layout` or `media`.
  final String scope;
  final String docId;
  final Map<String, TranslationEntry> fields;

  String get id => idFor(lang, scope, docId);

  TranslationEntry? entryFor(TranslationPath path) => fields[path.value];

  TranslationRecord withEntry(TranslationPath path, TranslationEntry entry) =>
      TranslationRecord(lang: lang, scope: scope, docId: docId, fields: {...fields, path.value: entry});

  /// Paths with a translation whose source no longer exists (its block,
  /// item or field was deleted). They are never matched to other content:
  /// new content always has new ids.
  Set<String> orphanPaths(Iterable<TranslationPath> current) {
    final live = {for (final p in current) p.value};
    return {for (final key in fields.keys) if (!live.contains(key)) key};
  }

  Map<String, dynamic> toMap() => {
        'lang': lang,
        'scope': scope,
        'docId': docId,
        'schemaVersion': schemaVersion,
        'fields': {for (final e in fields.entries) e.key: e.value.toMap()},
      };
}
